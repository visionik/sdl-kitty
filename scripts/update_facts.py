#!/usr/bin/env python3
"""Vendor the shared terminal facts, and compile both TOML files into the driver.

    python3 scripts/update_facts.py [path/to/terminal-facts]  # default: ../terminal-facts
    python3 scripts/update_facts.py --header                  # after editing config/sdl-kitty.toml
    python3 scripts/update_facts.py --check                   # fail if the header is stale (ctest)

Copies terminals.toml (github.com/visionik/terminal-facts) to config/, unchanged,
checks it with that repo's reference reader, records the commit in
config/terminals.source, and writes
third_party/SDL/src/video/kitty/SDL_kittyprofile_data.h from config/terminals.toml and
config/sdl-kitty.toml. Python 3.11+.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "config" / "terminals.toml"
SOURCE = ROOT / "config" / "terminals.source"
TUNING = ROOT / "config" / "sdl-kitty.toml"
HEADER = ROOT / "third_party" / "SDL" / "src" / "video" / "kitty" / "SDL_kittyprofile_data.h"


def c_string(name: str, text: str) -> str:
    lines = [f"static const char {name}[] ="]
    for line in text.splitlines(keepends=True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        lines.append(f'    "{escaped}"')
    lines[-1] += ";"
    return "\n".join(lines)


def check_tuning_ids() -> None:
    """Every [terminal.<id>] in sdl-kitty.toml names a row in terminals.toml, or unknown."""
    rows = {row["id"] for row in tomllib.loads(FACTS.read_text()).get("terminal", [])}
    tuning = tomllib.loads(TUNING.read_text()).get("terminal", {})
    stray = sorted(set(tuning) - rows - {"unknown"})
    if stray:
        sys.exit(f"{TUNING.name}: [terminal.<id>] for ids not in terminals.toml: {stray}")


def header() -> str:
    source = SOURCE.read_text().strip()
    return "\n".join(
        [
            "/*",
            "  Simple DirectMedia Layer",
            "  Copyright (C) 2026 Visionik <visionik@pobox.com>",
            "*/",
            "",
            "/*",
            " * Generated by sdl-kitty's scripts/update_facts.py: don't edit.",
            " *",
            " * KITTY_EMBEDDED_FACTS_TOML is sdl-kitty's config/terminals.toml, the",
            f" * shared facts from {source}.",
            " * KITTY_EMBEDDED_TUNING_TOML is sdl-kitty's config/sdl-kitty.toml.",
            " */",
            "#ifndef SDL_kittyprofile_data_h_",
            "#define SDL_kittyprofile_data_h_",
            "",
            f'#define KITTY_EMBEDDED_FACTS_SOURCE "{source}"',
            "",
            c_string("KITTY_EMBEDDED_FACTS_TOML", FACTS.read_text()),
            "",
            c_string("KITTY_EMBEDDED_TUNING_TOML", TUNING.read_text()),
            "",
            "#endif /* SDL_kittyprofile_data_h_ */",
            "",
        ]
    )


def vendor(repo: Path) -> None:
    git = ["git", "-C", str(repo)]
    commit = subprocess.run([*git, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    dirty = subprocess.run([*git, "status", "--porcelain", "terminals.toml"], capture_output=True, text=True, check=True)
    if dirty.stdout.strip():
        sys.exit(f"{repo} has uncommitted changes to terminals.toml: commit them first")
    sys.path.insert(0, str(repo))
    import terminal_facts  # the reference reader, from that checkout

    rows = terminal_facts.load(repo / "terminals.toml")
    shutil.copyfile(repo / "terminals.toml", FACTS)
    SOURCE.write_text(f"https://github.com/visionik/terminal-facts {commit}\n")
    print(f"terminal facts from {commit[:7]}: {len(rows)} rows")


def main() -> None:
    args = sys.argv[1:]
    if "--check" in args:
        check_tuning_ids()
        if not HEADER.exists() or HEADER.read_text() != header():
            sys.exit(f"{HEADER.name} is stale: run python3 scripts/update_facts.py --header")
        print(f"{HEADER.name} is up to date")
        return
    if "--header" not in args:
        vendor(Path(args[0] if args else ROOT.parent / "terminal-facts").resolve())
    check_tuning_ids()
    HEADER.write_text(header())
    print(f"wrote {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
